    public static string GetMeaning(string idiom)
    {
        foreach (var entry in Entries)
        {
            foreach (var partner in entry.IdiomPartners)
            {
                if (entry.Kanji + partner == idiom)
                {
                    return entry.Meaning;
                }
            }
        }

        return "";
    }
